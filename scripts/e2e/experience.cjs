const assert = require('node:assert/strict')
const path = require('node:path')
const fs = require('node:fs')
exports.run = async (vscode, workspace) => {
    const config = vscode.workspace.getConfiguration('opencmlLanguageServer')
    const original = config.get('camelPath')
    const open = async (name, text) => {
        const uri = vscode.Uri.file(path.join(workspace.uri.fsPath, name))
        await vscode.workspace.fs.writeFile(uri, Buffer.from(text))
        const doc = await vscode.workspace.openTextDocument(uri)
        await vscode.window.showTextDocument(doc)
        return doc
    }
    const replace = async (doc, text) => {
        const edit = new vscode.WorkspaceEdit()
        edit.replace(doc.uri, new vscode.Range(doc.positionAt(0), doc.positionAt(doc.getText().length)), text)
        assert(await vscode.workspace.applyEdit(edit))
    }
    const waitFor = async predicate => {
        for (let i = 0; i < 100; i++) { if (await predicate()) return; await new Promise(r => setTimeout(r, 100)) }
        assert.fail('Expected condition did not become true')
    }
    await vscode.commands.executeCommand('camel.restartServer')
    const report = await vscode.commands.executeCommand('camel.showRuntimeInfo')
    assert.equal(report.phase, 'native')
    assert(report.runtimeVersion.startsWith('Camel v'))
    assert(report.serverVersion)
    assert.equal(report.compatibility.minimumVersion, '0.2.11')
    assert.equal(report.compatibility.status, 'supported')
    assert.equal(report.compatibility.features.cliGir.supported, true)
    assert.equal(report.compatibility.features.nativeGir.supported, true)
    assert(report.files.find(file => file.name === 'Language server').exists)
    assert.equal(path.normalize(report.files[0].path), path.normalize(original))
    console.log('RUNTIME_NATIVE_OK')

    const doc = await open('advice.cml', 'func main(): int { return missing_advice_symbol }\n')
    await waitFor(() => vscode.languages.getDiagnostics(doc.uri).some(d => d.message.includes('missing_advice_symbol')))
    const diagnostic = vscode.languages.getDiagnostics(doc.uri).find(d => d.message.includes('missing_advice_symbol'))
    assert(diagnostic.message.includes(/^zh/i.test(vscode.env.language) ? '建议：' : 'Suggestion:'))
    const actions = await vscode.commands.executeCommand('vscode.executeCodeActionProvider', doc.uri, diagnostic.range, vscode.CodeActionKind.QuickFix.value)
    const action = actions.find(action => action.command?.command === 'camel.showDiagnosticAdvice')
    assert(action, 'no suggestion action for runtime diagnostic')
    assert(!action.edit, 'prose suggestion must not become an unverified edit')
    await vscode.commands.executeCommand(action.command.command, ...action.command.arguments)
    assert(vscode.window.activeTextEditor.document.getText().includes('Make sure the name is declared'))
    await vscode.commands.executeCommand('workbench.action.revertAndCloseActiveEditor')
    // Keep this unrelated open Camel buffer valid before the save-all-Camel run.
    await replace(doc, 'func main(): int { return 0 }\n')
    console.log('DIAGNOSTIC_ADVICE_OK')

    // Real native server: saved-only diagnostics must not disable live hover.
    await config.update('diagnostics.trigger', 'onSave', vscode.ConfigurationTarget.Workspace)
    await vscode.commands.executeCommand('camel.restartServer')
    const saved = await open('saved_checks.cml', 'func main(): int { return 0 }\n')
    await new Promise(r => setTimeout(r, 800))
    await replace(saved, 'func main(): int { return missing_saved_check }\n')
    await new Promise(r => setTimeout(r, 1200))
    assert.equal(vscode.languages.getDiagnostics(saved.uri).length, 0, 'onSave reported unsaved edits')
    await saved.save()
    await waitFor(() => vscode.languages.getDiagnostics(saved.uri).some(d => d.message.includes('missing_saved_check')))
    const savedDiagnostic = vscode.languages.getDiagnostics(saved.uri)[0]
    const savedCode = typeof savedDiagnostic.code === 'object' ? savedDiagnostic.code.value : savedDiagnostic.code
    await config.update('diagnostics.severityOverrides', { [String(savedCode)]: 'warning' }, vscode.ConfigurationTarget.Workspace)
    await vscode.commands.executeCommand('camel.restartServer')
    await waitFor(() => vscode.languages.getDiagnostics(saved.uri).some(d => d.severity === vscode.DiagnosticSeverity.Warning))
    await config.update('diagnostics.severityOverrides', { [String(savedCode)]: 'off' }, vscode.ConfigurationTarget.Workspace)
    await vscode.commands.executeCommand('camel.restartServer')
    await waitFor(() => vscode.languages.getDiagnostics(saved.uri).length === 0)
    await replace(saved, 'func main(): int { return 0 }\n')
    await saved.save()
    await config.update('diagnostics.trigger', undefined, vscode.ConfigurationTarget.Workspace)
    await config.update('diagnostics.severityOverrides', undefined, vscode.ConfigurationTarget.Workspace)
    await vscode.commands.executeCommand('camel.restartServer')
    console.log('DIAGNOSTIC_SETTINGS_OK')

    const liveLib = await open('live_lib.cml', 'module live_lib\nexport func increment(value: int): int { return value + 1 }\n')
    const liveMain = await open('live_main.cml', 'import { increment } from live_lib\nfunc main(): int {\n let answer = increment(2)\n return answer\n}\n')
    await new Promise(r => setTimeout(r, 600))
    assert.equal(vscode.languages.getDiagnostics(liveLib.uri).length, 0, 'library must not require main')
    await replace(liveLib, 'module live_lib\nexport func increment(value: float): float { return value + 1.0 }\n')
    await waitFor(() => vscode.languages.getDiagnostics(liveMain.uri).some(d => d.message.includes('No matching function')))
    await replace(liveLib, 'module live_lib\nexport func increment(value: int): int { return value + 1 }\n')
    await waitFor(() => vscode.languages.getDiagnostics(liveMain.uri).length === 0)
    const hintRange = new vscode.Range(0, 0, 5, 0)
    const hints = await vscode.commands.executeCommand('vscode.executeInlayHintProvider', liveMain.uri, hintRange)
    assert(hints.some(h => h.label === ': int'))
    assert(hints.some(h => h.label === 'value:'))
    await config.update('inlayHints.types', false, vscode.ConfigurationTarget.Workspace)
    const reducedHints = await vscode.commands.executeCommand('vscode.executeInlayHintProvider', liveMain.uri, hintRange)
    assert(!reducedHints.some(h => h.kind === vscode.InlayHintKind.Type))
    await config.update('inlayHints.types', undefined, vscode.ConfigurationTarget.Workspace)
    await liveLib.save()
    console.log('LIVE_WORKSPACE_LSP_OK: dependent diagnostics refresh without save and configurable inlay hints')

    const dep = await open('run_dep.cml', 'module run_dep\nexport func value(): int { return missing_dependency }\n')
    const main = await open('run_saved.cml', 'func main(): int { return missing_entry }\n')
    const depText = 'module run_dep\nexport func value(): int { return 0 }\n'
    const mainText = 'import { value } from run_dep\nfunc main(): int { return value() }\n'
    await replace(dep, depText)
    await replace(main, mainText)
    assert(dep.isDirty && main.isDirty)
    await vscode.window.showTextDocument(main)
    const code = await vscode.commands.executeCommand('camel.run')
    assert.equal(code, 0, 'run must compile the saved entry and dependency')
    assert(!dep.isDirty && !main.isDirty)
    assert.equal(fs.readFileSync(dep.uri.fsPath, 'utf8'), depText)
    assert.equal(fs.readFileSync(main.uri.fsPath, 'utf8'), mainText)
    console.log('SAVE_BEFORE_RUN_OK: current file and dirty dependency')

    try {
        await config.update('camelLsPath', path.join(workspace.uri.fsPath, 'missing-ls.exe'), vscode.ConfigurationTarget.Workspace)
        await vscode.commands.executeCommand('camel.restartServer')
        const failed = await vscode.commands.executeCommand('camel.showRuntimeInfo')
        assert.equal(failed.phase, 'failed')
        assert(failed.startupError.includes('missing-ls'))
        await config.update('camelLsPath', '', vscode.ConfigurationTarget.Workspace)
        await config.update('camelPath', path.join(workspace.uri.fsPath, 'missing-camel.exe'), vscode.ConfigurationTarget.Workspace)
        await vscode.commands.executeCommand('camel.restartServer')
        const fallback = await vscode.commands.executeCommand('camel.showRuntimeInfo')
        assert.equal(fallback.phase, 'fallback')
        assert(fallback.versionError)
        assert.equal(fallback.compatibility.status, 'unavailable')
        assert.equal(fallback.compatibility.features.cliDiagnostics.supported, false)
        assert.equal(fallback.compatibility.features.formatting.supported, false)
        assert(fallback.warnings.length)
        console.log('RUNTIME_FAILED_AND_FALLBACK_OK')
    } finally {
        await config.update('camelLsPath', '', vscode.ConfigurationTarget.Workspace)
        await config.update('camelPath', original, vscode.ConfigurationTarget.Workspace)
        await vscode.commands.executeCommand('camel.restartServer')
    }
}
