import fs from 'node:fs'
import assert from 'node:assert/strict'
import { loadTs as load } from './load-ts.mjs'
const { parseDot } = await load('webview/src/panels/graphviz/dot.ts')
const { buildFlowModel } = await load('webview/src/panels/graphviz/layout.ts')
const { focusGraph, moduleEntries, graphTarget } = await load('webview/src/panels/graphviz/hierarchy.ts')
const dot = parseDot('digraph G { subgraph A { a [label="a"]; subgraph B { b [label="b"]; c [label="c"]; b -> c [type="NORM"]; } } outside [label="outside"]; outside -> b [type="WITH", label="0|0"]; c -> a [type="CTRL"]; }')
const model = buildFlowModel(dot, {})
assert.equal(model.edges.length, 3, 'cross-scope edges lost')
const original = JSON.stringify(model)
const root = focusGraph(model, '')
assert.deepEqual(root.nodes.map(n => n.id), ['A', 'outside'])
assert.equal(root.edges.length, 1)
assert.equal(root.edges[0].target, 'A')
const nested = focusGraph(model, 'A/B')
assert.equal(nested.nodes.filter(n => n.id.startsWith('boundary:')).length, 2)
assert.equal(nested.edges.length, 3)
assert(nested.edges.some(e => e.edgeType === 'WITH' && e.target === 'A/B/b'))
assert(nested.edges.some(e => e.edgeType === 'CTRL' && e.source === 'A/B/c'))
assert.equal(JSON.stringify(model), original, 'navigation mutated full model')
assert.deepEqual(focusGraph({ nodes: [], edges: [] }, ''), { nodes: [], edges: [] })
console.log('GIR hierarchy: nested projection, boundaries, edge kinds, immutable full model passed')

const refs = buildFlowModel(parseDot('digraph G { subgraph child { label="f"; a [label="a"]; } subgraph unreferenced { label="g"; b [label="b"]; } caller [label="f", type="FUNC"]; }'), {})
const focused = focusGraph(refs, '')
assert.equal(focused.nodes.find(n => n.id === 'caller').data.enterScope, 'child')
assert.deepEqual(focused.nodes.filter(n => n.type === 'cluster').map(n => n.id), ['unreferenced'])
const ambiguous = buildFlowModel(parseDot('digraph G { subgraph x { label="f"; a [label="a"]; } subgraph y { label="f"; b [label="b"]; } caller [label="f", type="FUNC"]; }'), {})
assert.equal(focusGraph(ambiguous, '').nodes.filter(n => n.type === 'cluster').length, 2)
assert.equal(focusGraph(ambiguous, '').nodes.find(n => n.id === 'caller').data.enterScope, undefined)
console.log('FUNC navigation: exact unique child matching and ambiguous-card fallback passed')

const moduleModel = buildFlowModel(parseDot('digraph G { subgraph m { label="main"; caller [label="r5", type="FUNC"]; } subgraph r { label="r5"; self [label="r5", type="FUNC"]; } entry [label="Function(graph=main, tupleSlots=0)", type="DATA"]; call [label="CALL", type="CALL"]; entry -> call [type="WITH"]; }'), {})
assert.deepEqual([...moduleEntries(moduleModel)], ['m'])
assert.equal(focusGraph(moduleModel, '', true).nodes.filter(n => n.type === 'cluster').length, 0)
assert.equal(focusGraph(moduleModel, 'm').nodes.find(n => n.id === 'm/caller').data.enterScope, 'r')
assert.equal(focusGraph(moduleModel, 'r').nodes.find(n => n.id === 'r/self').data.enterScope, 'r')
if (process.env.GIR_CASE_FILE) {
 const { execFileSync } = await import('node:child_process')
 const dot = execFileSync(process.env.CAMEL_EXE_PATH || 'D:/Projects/Camel/out/latest/bin/camel.exe', ['--color', 'never', process.env.GIR_CASE_FILE, 'std::gir'], { encoding: 'utf8', maxBuffer: 16 * 1024 * 1024 })
 const real = buildFlowModel(parseDot(dot.slice(dot.indexOf('digraph'))), {})
 const entries = moduleEntries(real)
 assert.equal(entries.size, 1)
 assert.equal(real.nodes.find(n => n.id === [...entries][0]).data.label, 'main')
 assert.equal(focusGraph(real, '', true).nodes.filter(n => n.type === 'cluster').length, 0)
 for (const name of ['r1', 'r5', 'w29']) {
  const calls = real.nodes.filter(n => n.data.nodeType === 'FUNC' && n.data.label === name)
  assert(calls.length)
  for (const call of calls) assert.equal(real.nodes.find(n => n.id === graphTarget(real, call))?.data.label, name)
 }
 console.log('Real perm_query_types: main function value, cross-level r1/r5 and recursive w29 resolved')
}

const metadata = buildFlowModel(parseDot('digraph G { p [label="PORT", type="PORT", param_name="offset", param_kind="with", param_index="0", value_type="int"]; c [label="PORT", type="CLOSURE_PORT", param_name="count"]; f [label="FILL", type="FILL", value_type="int[]"]; old [label="FILL", type="FILL"]; }'), {})
assert.equal(metadata.nodes.find(n => n.id === 'p').data.label, 'offset')
assert.equal(metadata.nodes.find(n => n.id === 'c').data.label, 'count')
assert.equal(metadata.nodes.find(n => n.id === 'f').data.label, 'int[]')
assert.equal(metadata.nodes.find(n => n.id === 'old').data.label, 'FILL')
assert.equal(metadata.nodes.find(n => n.id === 'p').data.attrs.param_kind, 'with')
console.log('GIR metadata: explicit parameter names, FILL types and legacy fallback passed')
